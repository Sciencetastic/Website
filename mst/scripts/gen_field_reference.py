"""Generate FORMAT_FIELDS.md (ordered field list per serialized class) by tracing real projects.

usage: python scripts/gen_field_reference.py <a.MST> [<b.MST> ...] > FORMAT_FIELDS.md
Classes/fields that never occur in the given samples (e.g. rarely-used optional blocks) are shown from
the first sample that contains them.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from nesmaker_mst import MSTProject  # noqa: E402
from nesmaker_mst.schema_reader import Leaf, Node  # noqa: E402

TYPE = {'i32': 'int32', 'u32': 'uint32', 'u8': 'byte', 'bool': 'bool', 'str': 'string', 'bytes': 'raw bytes', 'char': 'char'}


def tokens(node):
    out = []
    for it in node._items:
        if isinstance(it, Leaf):
            nm = it.name if it.name and not it.name.startswith('$') else ('(temp %s)' % it.name if it.name else '(anon)')
            out.append((nm + ('[]' if it.idx is not None else ''), it.kind, None))
        else:
            out.append(('child object', 'node', it._cls))
    return out


def shape(node):
    """Rows (label, kind, cls, reps, group) -- consecutive identical items and repeated 2..6 item
    groups are collapsed so lists read as one pattern."""
    t = tokens(node)
    rows, i = [], 0
    while i < len(t):
        best = (1, 1)           # (period, reps)
        for per in range(1, 7):
            reps = 1
            while t[i:i + per] == t[i + reps * per:i + (reps + 1) * per] and i + (reps + 1) * per <= len(t):
                reps += 1
            if reps >= 2 and reps * per > best[0] * best[1]:
                best = (per, reps)
        per, reps = best
        if reps >= 2 and per == 1:
            rows.append((t[i][0], t[i][1], t[i][2], reps, 0))
        elif reps >= 2:
            for k in range(per):
                rows.append((t[i + k][0], t[i + k][1], t[i + k][2], reps, per))
        else:
            rows.append((t[i][0], t[i][1], t[i][2], 1, 0))
        i += per * reps if reps >= 2 else 1
    return rows


def main(paths):
    seen = {}
    for p in paths:
        proj = MSTProject.open(p)

        def walk(n):
            if n._cls not in seen:
                seen[n._cls] = shape(n)
            for c in n._items:
                if isinstance(c, Node):
                    walk(c)
        walk(proj.root)
    print('# NES Maker 4.5.9 `.MST` -- serialized field order per class (FileVersion 374)\n')
    print('Auto-generated by `scripts/gen_field_reference.py` from real projects. Order is the on-disk order.')
    print('Tables are run-length compressed: `xN` = repeated N times; `x N (group of k rows)` = the k rows that carry it\nrepeat together as one record N times.')
    print('`(temp vN)` = a value the loader keeps in a local (usually a count or a GUID length prefix) that has no\n'
          'model field name; `[]` = repeated/array element; `xN` = N consecutive repeats.\n')
    for cls in sorted(seen, key=lambda c: (c != 'MainGameModel', c)):
        print(f'## {cls}\n\n| # | field | type | repeats |\n|--:|---|---|--:|')
        for i, (lab, kind, c, n, grp) in enumerate(seen[cls]):
            t = ('-> ' + c) if kind == 'node' else TYPE.get(kind, kind)
            rep = '' if n == 1 else (f'x{n}' if not grp else f'x{n} (group of {grp} rows)')
            print(f'| {i} | {lab} | {t} | {rep} |')
        print()


if __name__ == '__main__':
    main(sys.argv[1:])
